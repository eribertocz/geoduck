"""Evidencia G1 pasos 4 y 5: comportamiento de DETACH en DuckDB (ver README.md)."""
import duckdb, os, tempfile, subprocess, sys
d=tempfile.mkdtemp(); p=os.path.join(d,"b.duckdb"); duckdb.connect(p).close()
def t(label, sql):
    try: con.execute(sql); print(f"  {label}: OK")
    except Exception as e: print(f"  {label}: {type(e).__name__}: {str(e).splitlines()[0][:130]}")
print("==", duckdb.__version__)
con=duckdb.connect()
t("detach root", "DETACH memory")
t("attach", f"ATTACH '{p}' AS b")
t("use b", "USE b")
t("detach default (b)", "DETACH b")
print("   current:", con.execute("select current_database()").fetchall(), [r[0] for r in con.execute("select database_name from duckdb_databases() where not internal").fetchall()])
t("use memory", "USE memory")
t("write", "CREATE TABLE b.t AS SELECT range x FROM range(1000)")
t("detach b", "DETACH b")
print("   wal after detach:", os.path.exists(p+".wal"))
r=subprocess.run([sys.executable,"-c",f"import duckdb;c=duckdb.connect({p!r});print(c.execute('select count(*) from t').fetchone()[0])"],capture_output=True,text=True); print("   other proc sees:", r.stdout.strip() or r.stderr.strip()[:100])
t("detach missing", "DETACH nada")
t("attach again", f"ATTACH '{p}' AS b")
t("begin", "BEGIN")
t("insert in tx", "INSERT INTO b.t VALUES (1)")
t("detach in tx", "DETACH b")
t("rollback", "ROLLBACK")
t("detach after rb", "DETACH b")
# reader open: arrow reader then detach (1.5 allows? )
t("attach3", f"ATTACH '{p}' AS b")
rd=con.sql("select * from b.t").to_arrow_reader(100)
t("detach with reader open", "DETACH b")
try: print("   reader rows:", sum(x.num_rows for x in rd))
except Exception as e: print("   reader err", type(e).__name__, str(e)[:80])
