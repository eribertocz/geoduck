"""Evidencia G1 paso 3: comportamiento de ATTACH en DuckDB (ver README.md). Uso: python attach_behaviour.py"""
import duckdb, os, tempfile, subprocess, sys, time
d=tempfile.mkdtemp()
def q(s): return "'"+s.replace("'","''")+"'"
def tryit(label, sql, con):
    try: con.execute(sql); print(f"  {label}: OK")
    except Exception as e: print(f"  {label}: {type(e).__name__}: {str(e).splitlines()[0][:150]}")
print("==", duckdb.__version__)
con=duckdb.connect()
missing=os.path.join(d,"no.duckdb")
tryit("RO missing", f"ATTACH {q(missing)} AS a (READ_ONLY)", con); print("   exists after RO:", os.path.exists(missing))
tryit("RW missing creates?", f"ATTACH {q(missing)} AS b", con); print("   exists after RW:", os.path.exists(missing)); con.execute("DETACH b")
empty=os.path.join(d,"empty.duckdb"); open(empty,"x").close()
tryit("RW empty file", f"ATTACH {q(empty)} AS e", con)
try:
    con.execute("CREATE TABLE e.t AS SELECT 1 x"); con.execute("DETACH e"); print("   empty->size", os.path.getsize(empty))
    c2=duckdb.connect(empty, read_only=True); print("   reopen ok", c2.execute("select * from t").fetchall()); c2.close()
except Exception as e: print("   empty err", type(e).__name__, str(e)[:120])
empty2=os.path.join(d,"empty2.duckdb"); open(empty2,"x").close()
tryit("RO empty file", f"ATTACH {q(empty2)} AS e2 (READ_ONLY)", con)
txt=os.path.join(d,"t.txt"); open(txt,"w").write("hola mundo"*100)
tryit("RW not duckdb", f"ATTACH {q(txt)} AS x", con)
tryit("RO not duckdb", f"ATTACH {q(txt)} AS x (READ_ONLY)", con)
good=os.path.join(d,"g.duckdb"); duckdb.connect(good).close()
tryit("RO good", f"ATTACH {q(good)} AS g (READ_ONLY)", con)
tryit("write to RO", "CREATE TABLE g.t(x int)", con)
tryit("alias conflict", f"ATTACH {q(missing)} AS G", con)
tryit("same file other alias", f"ATTACH {q(good)} AS g2 (READ_ONLY)", con)
tryit("same file RW while RO", f"ATTACH {q(good)} AS g3", con)
con.execute("DETACH g")
tryit("dir missing", f"ATTACH {q(os.path.join(d,'nodir','x.duckdb'))} AS nd", con)
tryit("alias system", f"ATTACH {q(good)} AS system (READ_ONLY)", con)
tryit("alias memory", f"ATTACH {q(good)} AS memory (READ_ONLY)", con)
tryit("alias temp", f"ATTACH {q(good)} AS temp (READ_ONLY)", con)
# lock from other process
p=subprocess.Popen([sys.executable,"-c",f"import duckdb,time;c=duckdb.connect({good!r});print('held',flush=True);time.sleep(30)"],stdout=subprocess.PIPE,text=True)
p.stdout.readline()
tryit("locked RW", f"ATTACH {q(good)} AS l1", con)
tryit("locked RO", f"ATTACH {q(good)} AS l2 (READ_ONLY)", con)
p.kill(); p.wait()
ro=os.path.join(d,"ro.duckdb"); duckdb.connect(ro).close(); os.chmod(ro,0o444)
tryit("RW on read-only file perms", f"ATTACH {q(ro)} AS r", con)
print("  dbs:", con.execute("select database_name from duckdb_databases() where not internal").fetchall())
